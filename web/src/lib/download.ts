/* ============================================================
   حفظُ ملفٍّ من المتصفّح.

   ═══ الخطأان اللذان عولجا هنا، وكلاهما يظهر على آيفون وحده ═══

   **العنصر لم يكن يُلحق بالمستند.** و`click()` على عنصرٍ خارج الشجرة لا
   يتنقّل في WebKit — فلا يقع شيء إطلاقاً: لا ملفّ ولا خطأ ولا حركة.
   ويعمل في كروم على سطح المكتب، فيمرّ الخطأ في كل تجربة إلا التي
   يُشتكى منها.

   **والعنوان كان يُبطَل فور النقر.** والتنزيل يبدأ بعد النقر لا معه، فقد
   يجد المتصفّحُ العنوانَ مُبطَلاً قبل أن يقرأ منه.

   ═══ ولا علامةَ ترتيبِ بايتات هنا ═══

   كانت `\uFEFF` تُضاف إلى كل ملفّ يُحفظ، وهي لازمةٌ لـCSV وحده — بها يقرأ
   Excel العربية سليمةً. وفي JSON تكسر `JSON.parse`، فيخرج ملفٌّ يبدو
   سليماً ويُرفض عند أول قراءة. فمكانُها بناءُ CSV لا حفظُ الملفّ، وهو
   موضعها في «المركز» و«العملاء».

   ═══ ولا مشاركة هنا ═══

   على آيفون يُسلَّم الملفّ لتطبيق ناف، وهو يعرضه في شاشةٍ فيها «مشاركة»
   و«إغلاق». فلا يُبنى في الويب زرُّ مشاركةٍ ثانٍ لما يملكه الغلاف.
   ============================================================ */

/** كم يبقى عنوانُ الكائن حيّاً بعد النقر — دقيقة تكفي أبطأ تنزيلٍ يبدأ. */
const REVOKE_AFTER_MS = 60_000;

/** يحفظ كائناً ملفّاً باسمه. */
export function saveBlob(blob: Blob, filename: string): void {
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  window.setTimeout(() => URL.revokeObjectURL(url), REVOKE_AFTER_MS);
}

/** يحفظ نصّاً ملفّاً باسمه ونوعه. */
export function saveText(content: string, filename: string, type: string): void {
  saveBlob(new Blob([content], { type }), filename);
}
