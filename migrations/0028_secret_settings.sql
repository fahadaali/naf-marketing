-- بادئة محجوزة للأسرار داخل جدول الإعدادات.
--
-- ‏`GET /api/settings` يردّ الجدول كلَّه ويكتفي بـrequireAuth بلا صلاحية —
-- وتعليقه كان يقول «لا أسرار هنا». ثم صار مسارُ تسجيل خطّاف SocialAPI
-- يكتب سرّ توقيع HMAC في الجدول نفسه، فصار كلُّ عضوٍ مسجَّل — والدور
-- الافتراضي لأوّل داخلٍ من المركز هو `writer` — يقرأ السرّ.
--
-- والحلّ بنيويّ لا بقائمةِ أسماء: ما بدأ بـ`secret:` لا يخرج من مسار
-- القراءة ولا يُقبل في مسار الكتابة. فأيّ سرٍّ يُضاف بعد اليوم محميّ
-- باسمه لا بذاكرة من يضيفه.
--
-- والهجرة تنقل الصفَّ القائم بقيمته، فلا يحتاج أحدٌ إعادة تسجيل الخطّاف.
UPDATE settings SET key = 'secret:socialapi_webhook' WHERE key = 'socialapi_webhook_secret';
