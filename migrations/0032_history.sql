-- ═══ السجلّ كلّه، لا أسبوعاه الأخيران ═══
--
-- ── الصندوق ──
-- كانت ردودنا من تطبيق المنصّة تُفحص على تعليقات الأسبوعين الأخيرين وحدها،
-- وقائمة المنشورات تُقرأ صفحتين. فتعليقٌ قديم رُدّ عليه من هناك يبقى «بلا رد»
-- أبداً، ومنشورٌ قديم لا يُقرأ أصلاً.
--
-- وسحبُ السجلّ يمرّ على القديم مرّة، ثم يدور على التعليقات القديمة بلا رد
-- يفحص ردودها من جديد كل أسبوع. ويحتاج لذلك معرّفَ المزوّد للتعليق
-- (`sapi_cmt_…`): بعض الحسابات لا تُقرأ ردودها إلا به، وهو لا يُستعاد من
-- الترميز القديم `منشور|حساب|تعليق`. فيُحفظ من الآن مع كل تعليق يُقرأ.
ALTER TABLE platform_comments ADD COLUMN provider_interaction_id TEXT;

-- ── لقطات المنشورات ──
-- متى طُلبت أرقام المنشور الحيّة آخر مرّة، أجاب المزوّد بأرقامٍ أم لم يُجب.
-- بدونه يبقى منشورٌ لا يردّ المزوّد أرقامه أوّلَ القائمة في كل سحب — وقت
-- أرقامه لا يتقدّم — فيأكل حصّتها ولا يبلغ غيرَه شيء.
ALTER TABLE analytics_snapshots ADD COLUMN metrics_checked_at TEXT;
