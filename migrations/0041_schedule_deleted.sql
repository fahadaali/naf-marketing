-- ═══ منشورٌ حُذف من منصته ═══
--
-- الموعد المنشور يبقى بعد حذف منشوره من المنصة — فيه وقت النشر ومعرّفه، وما
-- سُحب من أرقامه قبل الحذف باقٍ في اللقطات. فلا يُمحى صفّه ولا تتغيّر حالته
-- (`status` مقيّدةٌ بأربع)، ويُكتب هنا وقتُ الحذف. والفارغ: منشورٌ قائم.
--
-- وبه يُجدوَل المحتوى على المنصة نفسها من جديد: «ما نُشر عليه لا يُجدوَل
-- ثانيةً» يعني ما بقي منشوراً عليها.
