-- نتيجة آخر طلبٍ لتعليقات المنشور من Ayrshare.
--
-- كان المنشور يُختم «مقروءاً» سواءٌ ردّ المزوّد بقائمةٍ فارغة أم رفضه («غير
-- موجود» أو رفضٌ يخصّه)، فلا يفرّق تقرير التغطية بين منشورٍ لا تعليق عليه
-- ومنشورٍ لم تصل تعليقاته أصلاً. والقيم: 'ok' قُرئ، 'not_found' ردّه «غير موجود»،
-- 'rejected' رفضه المزوّد لسببٍ يخصّه. وفارغٌ: قُرئ قبل هذه الهجرة.
ALTER TABLE inbox_post_state ADD COLUMN outcome TEXT;

-- وما قُرئ قبلها لا تُعرف نتيجته، فيُعاد طلبه مرّةً بحصّة الدورات المعتادة:
-- الحديث في الدورة العادية والقديم في دورة السجلّ. لا يُحذف شيء.
UPDATE inbox_post_state SET synced_at = NULL WHERE account_id LIKE 'ayrshare:%';
