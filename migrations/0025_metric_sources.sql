-- ===== وصلُ مؤشراتٍ كانت بلا مصدر =====
-- ستةٌ وعشرون مؤشراً في الدليل لم يكن لها مصدرٌ عامل: منها ما مزوّده مربوطٌ
-- أصلاً ولم يُقرأ منه، ومنها ما ينتظر مزوّداً لم يُختر بعد. ويُوصل بهذه
-- الدفعة ثمانيةٌ منها — ما لا يحتاج اشتراكاً ولا قراراً بالشراء. وخمسةٌ من
-- الثمانية كان تسجيلها في الدليل صحيحاً وينقصها الاحتساب وحده، فليس لها هنا
-- سطر: التغيير في `adapters/sources.ts` لا في التعريف.
--
-- والباقي مذكورٌ في `docs/naf-metrics.md` جدولاً بمزوّدٍ مقترحٍ وكلفته، لا
-- يُطبَّق منه شيء قبل اختيار المزوّد: مؤشرٌ يبقى بلا قيمة ثغرةٌ معلومة،
-- ومؤشرٌ يُوصل بمزوّدٍ لم يُتّفق عليه رقمٌ لا أحد يعرف من أين جاء.

-- ── مصدرٌ تاسع: مزوّد النشر ──
-- مسجَّل `social` في `naf-terms.md` §١٣. ولا مفتاح له: هو المزوّد المضبوط في
-- «الإعدادات ← المنصات والمزوّد» بمفتاحه نفسه، فلا يظهر في الشاشة حقلٌ يُملأ
-- — يُربط فيُقرأ منه.
--
-- ومقاييس المنشورات ليست منه: تلك تصل مع كل منشور وتُحتسب في الطبقتين
-- الأولى والثانية. وما هنا أرقامُ الحساب نفسه — متابعوه ومراجعاته.
INSERT OR IGNORE INTO integrations (key, is_enabled, config_json) VALUES
  ('social', 0, '{}');

-- ── إجمالي المتابعين: من مُدخَلٍ إلى مسحوب ──
-- كان يُسجَّل باليد شهرياً لكل منصّة، وعليه يقوم «معدل النمو في المتابعين».
-- ومزوّد النشر يعلن العدد مع كل حساب مربوط، فلا معنى لنقله بالنظر.
--
-- والتسجيل باليد يبقى ممكناً: منصّةٌ لا يُعلن المزوّد عددها تُسجَّل كما كانت،
-- والقيمة المسجّلة تحمل اسم من أدخلها كما تحمل المسحوبةُ اسم مصدرها.
UPDATE metric_definitions
SET source = 'integration', integration_key = 'social'
WHERE key = 'followers_total';

-- ── مراجعات الملف التجاري وتقييمه: من «الملف التجاري» إلى مزوّد النشر ──
-- الرقم رقمُ جوجل في الحالين. والفرق أن واجهة المراجعات في جوجل لا تزال
-- الإصدار الرابع وتحتاج اعتماداً مستقلاً للحساب قبل أن تردّ حرفاً، ومزوّد
-- النشر يقرأها اليوم بالمفتاح القائم ويُظهرها في الصندوق أصلاً.
--
-- ولا يُحتسبان من المراجعات المسحوبة إلى الصندوق: الصندوق يُسقط ما لا نصّ له
-- — تقييمَ نجومٍ بلا تعليق — فمتوسّطه متوسّطُ من كتب لا متوسّطُ من قيّم.
-- والمقروء هنا ملخّصُ المزوّد نفسه: العدد الكلّي والمتوسط المعلن.
UPDATE metric_definitions
SET integration_key = 'social'
WHERE key IN ('gbp_reviews', 'gbp_rating');
